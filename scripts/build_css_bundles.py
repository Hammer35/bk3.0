"""Build single-request CSS files from the editable source stylesheets."""

from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
CSS = ROOT / "static" / "css"

APP_SOURCES = (
    "tokens.css",
    "base.css",
    "components/buttons.css",
    "components/panels.css",
    "components/forms.css",
    "components/dialogs.css",
    "components/interface-scale.css",
    "components/workbench.css",
    "components/strategy.css",
    "components/language-switch.css",
    "shell.css",
)
LANDING_SOURCES = ("components/interface-scale.css", "components/language-switch.css", "landing.css")


def render(sources: tuple[str, ...]) -> str:
    """The bundle text for the given source files (pure: nothing is written)."""
    chunks = ["/* Generated by scripts/build_css_bundles.py. Edit source CSS files. */\n"]
    for source in sources:
        content = (CSS / source).read_text(encoding="utf-8")
        if "@import" in content:
            raise ValueError(f"Unexpected CSS import in {source}")
        chunks.append(f"\n/* {source} */\n{content.rstrip()}\n")
    return "".join(chunks)


def build(output: str, sources: tuple[str, ...]) -> None:
    path = CSS / output
    result = render(sources)
    if not path.exists() or path.read_text(encoding="utf-8") != result:
        path.write_text(result, encoding="utf-8")


if __name__ == "__main__":
    build("app.css", APP_SOURCES)
    build("landing.bundle.css", LANDING_SOURCES)
